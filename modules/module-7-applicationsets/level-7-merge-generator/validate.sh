#!/bin/bash
set -uo pipefail
source "$AM_LIB"

SET=parcel-api
kubectl -n argocd get applicationset "$SET" -o json >"$AM_TMP/set.json" 2>/dev/null \
  || am_fail "ApplicationSet '$SET' does not exist in namespace argocd"
jq -e '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' "$AM_TMP/set.json" >/dev/null \
  || am_fail "ApplicationSet '$SET' reports an error condition"

# The environments must still come from one merge generator (base + overrides) whose lists can be matched by key.
jq -e '.spec.generators | length == 1 and (.[0].merge != null)' "$AM_TMP/set.json" >/dev/null \
  || am_fail "ApplicationSet '$SET' no longer combines its base and override lists with a merge generator"
jq -e '.spec.generators[0].merge as $m
       | ($m.generators | length) >= 2
         and ([ $m.generators[] | .list.elements[]? | . as $e | $m.mergeKeys | all(. as $k | $e | has($k)) ] | all)' \
     "$AM_TMP/set.json" >/dev/null \
  || am_fail "The merge generator of '$SET' has list elements that its mergeKeys cannot match between the lists"
am_ok "ApplicationSet '$SET' merges its base and override lists on keys every element has"

want="parcel-api-dev parcel-api-prod parcel-api-stage"
have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name] | sort | join(" ")')"
[ "$have" = "$want" ] || am_fail "The Applications in argocd are [$have], expected [$want]"

for e in dev stage prod; do
  app="parcel-api-$e"
  owner="$(am_app "$app" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
  [ "$owner" = "$SET" ] || am_fail "Application '$app' is not generated by ApplicationSet '$SET' (owner: ${owner:-none})"
  [ "$(am_app "$app" '{.spec.destination.namespace}')" = "parcel-$e" ] \
    || am_fail "Application '$app' does not deploy to namespace parcel-$e"
  am_require_app_at_head "$app" parcel-api
done

declare -A want_replicas=([dev]=1 [stage]=1 [prod]=3)
declare -A want_body=([dev]="parcel-api dev" [stage]="parcel-api stage" [prod]="parcel-api prod priority-lane")
for e in dev stage prod; do
  ns="parcel-$e"
  am_wait_rollout deploy/parcel-api "$ns" 60s
  n="$(am_ready_replicas parcel-api "$ns")"
  [ "$n" = "${want_replicas[$e]}" ] || am_fail "Deployment parcel-api in $ns has $n ready replicas, expected ${want_replicas[$e]}"
  body="$(am_http "http://parcel-api.$ns" "$ns")" || am_fail "Service parcel-api in $ns does not answer"
  [ "$body" = "${want_body[$e]}" ] || am_fail "Service parcel-api in $ns answers '$body', expected '${want_body[$e]}'"
done
am_pass "production runs its override and dev/stage keep the defaults, all generated by the ApplicationSet"
