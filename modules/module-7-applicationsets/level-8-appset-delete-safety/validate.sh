#!/bin/bash
set -uo pipefail
source "$AM_LIB"

kubectl -n argocd get applicationset kiosk-fleet -o json >"$AM_TMP/set.json" 2>/dev/null \
  || am_fail "ApplicationSet 'kiosk-fleet' does not exist in namespace argocd"
jq -e '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' "$AM_TMP/set.json" >/dev/null \
  || am_fail "ApplicationSet 'kiosk-fleet' reports an error condition"
kubectl -n argocd get applicationset kiosk-apps >/dev/null 2>&1 \
  && am_fail "ApplicationSet 'kiosk-apps' still exists next to 'kiosk-fleet'"
am_ok "ApplicationSet kiosk-fleet exists, kiosk-apps is gone"

want="kiosk-east kiosk-north kiosk-south"
have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name] | sort | join(" ")')"
[ "$have" = "$want" ] || am_fail "The Applications in argocd are [$have], expected [$want]"

kubectl -n argocd get configmap argomissions-kiosk-baseline -o json >"$AM_TMP/base.json" 2>/dev/null \
  || am_fail "The record of the workloads that were running at the start of the mission is missing"

for r in north south east; do
  app="kiosk-$r"; ns="kiosk-$r"
  owner="$(am_app "$app" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
  [ "$owner" = kiosk-fleet ] || am_fail "Application '$app' is not generated by ApplicationSet 'kiosk-fleet' (owner: ${owner:-none})"
  am_require_app_at_head "$app" kiosk-web

  for kind in deploy svc; do
    now="$(am_jsonpath "$kind/kiosk-web" '{.metadata.uid}' "$ns")"
    was="$(jq -r --arg k "$kind-$r" '.data[$k] // empty' "$AM_TMP/base.json")"
    [ -n "$now" ] || am_fail "$kind/kiosk-web does not exist in namespace $ns"
    [ "$now" = "$was" ] || am_fail "$kind/kiosk-web in namespace $ns is a new object: the one that was serving at the start of the mission was deleted"
  done
  [ "$(am_ready_replicas kiosk-web "$ns")" -ge 2 ] || am_fail "Deployment kiosk-web in $ns has fewer than 2 ready pods"
  body="$(am_http "http://kiosk-web.$ns" "$ns")" || am_fail "Service kiosk-web in $ns does not answer"
  [ "$body" = "kiosk-web v2.4" ] || am_fail "Service kiosk-web in $ns answers '$body'"
done
am_pass "kiosk-fleet owns the apps and the original workloads never went away"
