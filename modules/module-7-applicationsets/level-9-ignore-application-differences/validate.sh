#!/bin/bash
set -uo pipefail
source "$AM_LIB"

SET=feedhub
kubectl -n argocd get applicationset "$SET" -o json >"$AM_TMP/set.json" 2>/dev/null \
  || am_fail "ApplicationSet '$SET' does not exist in namespace argocd"
jq -e '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' "$AM_TMP/set.json" >/dev/null \
  || am_fail "ApplicationSet '$SET' reports an error condition"

want="feedhub-dev feedhub-prod feedhub-stage"
have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name] | sort | join(" ")')"
[ "$have" = "$want" ] || am_fail "The Applications in argocd are [$have], expected [$want]"
for e in dev stage prod; do
  owner="$(am_app "feedhub-$e" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
  [ "$owner" = "$SET" ] || am_fail "Application 'feedhub-$e' is not generated by ApplicationSet '$SET' (owner: ${owner:-none})"
done

# Give the ApplicationSet controller time to take a manual change back, then look.
sleep 8
declare -A branch=([dev]=main [stage]=main [prod]=hotfix-1.8.1)
declare -A text=([dev]="feedhub v1.8" [stage]="feedhub v1.8" [prod]="feedhub v1.8.1-hotfix")
for e in dev stage prod; do
  app="feedhub-$e"
  rev="$(am_app "$app" '{.spec.source.targetRevision}')"
  [ "$rev" = "${branch[$e]}" ] || am_fail "Application '$app' tracks '${rev:-<none>}', expected ${branch[$e]}"
  am_require_app_at_head "$app" feedhub "${branch[$e]}"
  body="$(am_http "http://feedhub.feedhub-$e" "feedhub-$e")" || am_fail "Service feedhub in feedhub-$e does not answer"
  [ "$body" = "${text[$e]}" ] || am_fail "Service feedhub in feedhub-$e answers '$body', expected '${text[$e]}'"
done
am_pass "feedhub-prod runs the hotfix branch and the ApplicationSet leaves it alone"
