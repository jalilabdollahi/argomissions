#!/bin/bash
set -uo pipefail
source "$AM_LIB"

SET=harbor
kubectl -n argocd get applicationset "$SET" >/dev/null 2>&1 \
  || am_fail "ApplicationSet '$SET' does not exist in namespace argocd"
kubectl -n argocd get applicationset "$SET" -o json | jq -e \
  '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' >/dev/null \
  || am_fail "ApplicationSet '$SET' is still reporting an error: $(kubectl -n argocd get applicationset "$SET" -o jsonpath='{.status.health.message}')"

want="dock-api dock-notify dock-tracker"
have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name] | sort | join(" ")')"
[ "$have" = "$want" ] || am_fail "The Applications in argocd are [${have}], expected [$want]"

for s in $want; do
  owner="$(am_app "$s" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
  [ "$owner" = "$SET" ] || am_fail "Application '$s' is not generated by ApplicationSet '$SET' (owner: ${owner:-none})"
  p="$(am_app "$s" '{.spec.source.path}')"
  [ "${p%/}" = "services/$s" ] || am_fail "Application '$s' deploys path '${p}', expected services/$s"
  ns="$(am_app "$s" '{.spec.destination.namespace}')"
  [ "$ns" = harbor ] || am_fail "Application '$s' deploys to namespace '${ns:-<none>}', expected harbor"
  am_require_app_at_head "$s" harbor-services
  body="$(am_http "http://$s.harbor" harbor)" || am_fail "Service $s in namespace harbor does not answer"
  [ "$body" = "$s v1" ] || am_fail "Service $s answers '$body'"
done
am_pass "the ApplicationSet generates all three services and they answer"
