#!/bin/bash
set -uo pipefail
source "$AM_LIB"

SET=pulse-previews
kubectl -n argocd get applicationset "$SET" -o json >"$AM_TMP/set.json" 2>/dev/null \
  || am_fail "ApplicationSet '$SET' does not exist in namespace argocd"
jq -e '.spec.generators | length == 1 and (.[0].pullRequest.gitea != null)' "$AM_TMP/set.json" >/dev/null \
  || am_fail "ApplicationSet '$SET' no longer discovers pull requests through the Gitea pull request generator"
jq -e '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' "$AM_TMP/set.json" >/dev/null \
  || am_fail "ApplicationSet '$SET' reports an error condition"

am_gitea GET "/repos/platform/pulse-web/pulls?state=all&limit=50" >"$AM_TMP/prs.json" \
  || am_fail "Cannot read the pull requests of pulse-web from Gitea"
n_open="$(jq -r '[.[] | select(.head.ref=="checkout-redesign")][0].number' "$AM_TMP/prs.json")"
n_closed="$(jq -r '[.[] | select(.head.ref=="legacy-cleanup")][0].number' "$AM_TMP/prs.json")"
n_plain="$(jq -r '[.[] | select(.head.ref=="wip-search")][0].number' "$AM_TMP/prs.json")"
[ "$(jq -r '[.[] | select(.head.ref=="checkout-redesign")][0].state' "$AM_TMP/prs.json")" = open ] \
  || am_fail "The pull request of branch checkout-redesign is no longer open"

have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name] | sort | join(" ")')"
[ -n "$have" ] || am_fail "There is no preview Application: the open, labelled pull request has no environment"
[ "$have" = "pulse-pr-$n_open" ] || am_fail "The Applications in argocd are [$have], expected only [pulse-pr-$n_open]"

app="pulse-pr-$n_open"
owner="$(am_app "$app" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
[ "$owner" = "$SET" ] || am_fail "Application '$app' is not generated by ApplicationSet '$SET' (owner: ${owner:-none})"
head="$(am_repo_head pulse-web checkout-redesign)"
[ "$(am_app "$app" '{.spec.source.targetRevision}')" = "$head" ] \
  || [ "$(am_app "$app" '{.spec.source.targetRevision}')" = checkout-redesign ] \
  || am_fail "Application '$app' does not track the PR branch"
[ "$(am_app "$app" '{.spec.destination.namespace}')" = "$app" ] || am_fail "Application '$app' does not deploy to namespace $app"
am_require_app_at_head "$app" pulse-web checkout-redesign

body="$(am_http "http://pulse-web.$app" "$app")" || am_fail "Service pulse-web in namespace $app does not answer"
[ "$body" = "pulse-web checkout-redesign" ] || am_fail "Service pulse-web in $app answers '$body'"

for n in "$n_closed" "$n_plain"; do
  kubectl get namespace "pulse-pr-$n" >/dev/null 2>&1 && am_fail "Namespace pulse-pr-$n exists, but that pull request is not meant to have a preview"
done
am_pass "only the open, labelled pull request has a preview environment"
