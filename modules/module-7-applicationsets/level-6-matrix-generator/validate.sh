#!/bin/bash
set -uo pipefail
source "$AM_LIB"

SET=mesh
kubectl -n argocd get applicationset "$SET" >/dev/null 2>&1 \
  || am_fail "ApplicationSet '$SET' does not exist in namespace argocd"
kubectl -n argocd get applicationset "$SET" -o json | jq -e \
  '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' >/dev/null \
  || am_fail "ApplicationSet '$SET' is still reporting an error: $(kubectl -n argocd get applicationset "$SET" -o jsonpath='{.status.health.message}')"

want="invoicer-prod invoicer-staging mailer-prod mailer-staging"
have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name] | sort | join(" ")')"
[ "$have" = "$want" ] || am_fail "The Applications in argocd are [${have}], expected [$want]"

for s in invoicer mailer; do
  for e in staging prod; do
    app="$s-$e"
    owner="$(am_app "$app" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
    [ "$owner" = "$SET" ] || am_fail "Application '$app' is not generated by ApplicationSet '$SET' (owner: ${owner:-none})"
    p="$(am_app "$app" '{.spec.source.path}')"
    [ "${p%/}" = "services/$s" ] || am_fail "Application '$app' deploys path '${p}', expected services/$s"
    ns="$(am_app "$app" '{.spec.destination.namespace}')"
    [ "$ns" = "$s-$e" ] || am_fail "Application '$app' deploys to namespace '${ns:-<none>}', expected $s-$e"
    am_require_app_at_head "$app" mesh-services
    body="$(am_http "http://$s.$s-$e" "$s-$e")" || am_fail "Service $s in namespace $s-$e does not answer"
    [ "$body" = "$s $e" ] || am_fail "Service $s in namespace $s-$e answers '$body', expected '$s $e'"
  done
done
am_pass "every service runs in every environment, one Application each"
