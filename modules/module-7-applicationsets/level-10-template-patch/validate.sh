#!/bin/bash
set -uo pipefail
source "$AM_LIB"

SET=lumen-gateway
kubectl -n argocd get applicationset "$SET" -o json >"$AM_TMP/set.json" 2>/dev/null \
  || am_fail "ApplicationSet '$SET' does not exist in namespace argocd"
jq -e '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' "$AM_TMP/set.json" >/dev/null \
  || am_fail "ApplicationSet '$SET' reports an error condition"

want="lumen-dev lumen-prod lumen-stage"
have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name] | sort | join(" ")')"
[ "$have" = "$want" ] || am_fail "The Applications in argocd are [$have], expected [$want]"
for e in dev stage prod; do
  owner="$(am_app "lumen-$e" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
  [ "$owner" = "$SET" ] || am_fail "Application 'lumen-$e' is not generated by ApplicationSet '$SET' (owner: ${owner:-none})"
done

# Let the ApplicationSet controller undo a hand-edited sync policy before we look.
sleep 6
for e in dev stage; do
  [ "$(am_app "lumen-$e" '{.spec.syncPolicy.automated}')" = "" ] \
    || am_fail "Application 'lumen-$e' has an automated sync policy; QA needs it manual"
done
[ "$(am_app lumen-prod '{.spec.syncPolicy.automated}')" != "" ] \
  || am_fail "Application 'lumen-prod' has no automated sync policy"
[ "$(am_app lumen-prod '{.spec.syncPolicy.automated.prune}')" = true ] \
  || am_fail "Application 'lumen-prod' does not prune on automated sync"
am_ok "only lumen-prod has an automated sync policy (with prune)"

am_require_app_at_head lumen-prod lumen-gateway
body="$(am_http http://lumen-gateway.lumen-prod lumen-prod)" || am_fail "Service lumen-gateway in lumen-prod does not answer"
[ "$body" = "lumen-gateway v2" ] || am_fail "Service lumen-gateway in lumen-prod answers '$body'"

for e in dev stage; do
  body="$(am_http "http://lumen-gateway.lumen-$e" "lumen-$e")" || am_fail "Service lumen-gateway in lumen-$e does not answer"
  [ "$body" = "lumen-gateway v1" ] || am_fail "Service lumen-gateway in lumen-$e answers '$body': the frozen rig was moved"
done
am_pass "prod follows main by itself while dev and stage stay frozen"
