#!/bin/bash
set -uo pipefail
source "$AM_LIB"

bad=0
bad() { echo "❌ $1"; bad=$((bad + 1)); }

SET=orbit-fleet
SVC_URL="$(am_repo_url orbit-services)"

# ── the Git side: the fix is a new commit, the audit trail is intact ────────
if am_repo_checkout orbit-control "$AM_TMP/control"; then
  git -C "$AM_TMP/control" log --format=%s | grep -qx "Simplify generator globs" \
    && am_ok "The history of orbit-control is intact (the tidy-up commit is still in the log)" \
    || bad "The history of orbit-control was rewritten: the commit that caused the outage is gone from the log"
else
  bad "cannot clone the orbit-control repo"
fi
if am_app_exists orbit-control; then
  if [ "$(am_app orbit-control '{.spec.syncPolicy.automated.selfHeal}')" != true ] || [ "$(am_app orbit-control '{.spec.syncPolicy.automated.prune}')" != true ]; then
    bad "Application 'orbit-control' is not automated any more: a change merged to Git does not reach the cluster unless somebody syncs by hand"
  fi
  sync="$(am_app_sync orbit-control)"; rev="$(am_app_rev orbit-control)"; head="$(am_repo_head orbit-control)"
  if [ "$sync" = Synced ] && [ "$rev" = "$head" ] && [ "$(am_app_health orbit-control)" = Healthy ]; then
    am_ok "Application 'orbit-control' is Synced and Healthy at orbit-control@${head:0:7}"
  else
    bad "Application 'orbit-control' is ${sync:-Unknown}/$(am_app_health orbit-control) at ${rev:0:7} (orbit-control/main is at ${head:0:7})"
  fi
else
  bad "Application 'orbit-control' does not exist"
fi

# ── the ApplicationSet and what it generates ────────────────────────────────
if ! kubectl -n argocd get applicationset "$SET" -o json >"$AM_TMP/set.json" 2>/dev/null; then
  bad "ApplicationSet '$SET' does not exist"
else
  jq -e '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' "$AM_TMP/set.json" >/dev/null \
    || bad "ApplicationSet '$SET' reports an error condition"
fi
have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name | select(startswith("orbit-")) | select(. != "orbit-control")] | sort | join(" ")')"
[ "$have" = "orbit-alerts orbit-ingest orbit-rollup" ] || bad "The Orbit Applications in argocd are [$have], expected [orbit-alerts orbit-ingest orbit-rollup]"

head="$(am_repo_head orbit-services)"
for s in ingest rollup alerts; do
  app="orbit-$s"
  am_app_exists "$app" || continue
  owner="$(am_app "$app" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
  if [ "$owner" != "$SET" ]; then
    bad "Application '$app' is not generated by ApplicationSet '$SET' (owner: ${owner:-nobody}): the set cannot manage it"
    continue
  fi
  [ "$(am_app "$app" '{.spec.project}')" = orbit ] || bad "Application '$app' is not in project orbit"
  sync="$(am_app_sync "$app")"; rev="$(am_app_rev "$app")"; health="$(am_app_health "$app")"
  if [ "$sync" = Synced ] && [ "$rev" = "$head" ] && [ "$health" = Healthy ]; then
    body="$(am_http "http://orbit-$s.orbit-$s" "orbit-$s" 2)" || body="(no answer)"
    [ "$body" = "orbit-$s v1" ] && am_ok "orbit-$s is generated, Synced, Healthy and answering" || bad "Service orbit-$s answers '$body'"
  else
    bad "Application '$app' is ${sync:-Unknown}/${health:-Unknown}: $(am_app_conditions "$app" | head -1 | cut -c1-170)"
  fi
done

# ── the project is still a boundary ─────────────────────────────────────────
kubectl -n argocd get appproject orbit -o json >"$AM_TMP/project.json" 2>/dev/null || bad "AppProject 'orbit' does not exist"
if [ -s "$AM_TMP/project.json" ]; then
  jq -e --arg u "${SVC_URL%.git}" '[.spec.sourceRepos[]? | select(. == "*" or (rtrimstr(".git") == $u))] | length > 0' "$AM_TMP/project.json" >/dev/null \
    || bad "Project orbit does not allow the repository the services are read from"
  jq -e '[.spec.sourceRepos[]? | select(. == "*")] | length == 0' "$AM_TMP/project.json" >/dev/null \
    || bad "Project orbit allows every repository: it is no longer a boundary"
  jq -e '[.spec.destinations[]? | select((.namespace // "") == "*")] | length == 0' "$AM_TMP/project.json" >/dev/null \
    || bad "Project orbit allows every namespace: it is no longer a boundary"
fi

# ── the next mistake must not delete workloads ──────────────────────────────
preserve="$(jq -r '.spec.syncPolicy.preserveResourcesOnDeletion // false' "$AM_TMP/set.json" 2>/dev/null)"
fins="$(kubectl -n argocd get applications -o json | jq -r '[.items[] | select(.metadata.name | startswith("orbit-")) | select((.metadata.finalizers // []) | index("resources-finalizer.argocd.argoproj.io"))] | length')"
if [ "$preserve" = true ] && [ "$fins" = 0 ]; then
  am_ok "Deleting a generated Application no longer deletes its workloads"
else
  bad "A generated Application still carries the resources finalizer: the next generator mistake deletes workloads again"
fi

[ "$bad" -eq 0 ] || { echo "❌ $bad problem(s) left in the Orbit fleet"; exit 1; }
am_pass "The fleet is back from Git, history intact, and the next deletion cannot take the workloads with it"
