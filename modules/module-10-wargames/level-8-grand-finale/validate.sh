#!/bin/bash
set -uo pipefail
source "$AM_LIB"

ROOT=meridian-root
fails=0
bad() { echo "❌ $*"; fails=$((fails+1)); }
good() { am_ok "$*"; }

am_app_exists "$ROOT" || am_fail "Application '$ROOT' does not exist in namespace argocd"
head="$(am_repo_head meridian-platform)"
am_repo_checkout meridian-platform "$AM_TMP/git" >/dev/null 2>&1 || am_fail "cannot clone meridian-platform"

# ── The root and what it owns ───────────────────────────────────────────────────
s="$(am_app_sync $ROOT)"; h="$(am_app_health $ROOT)"; r="$(am_app_rev $ROOT)"
if [ "$s" != Synced ] || [ "$h" != Healthy ] || [ "$r" != "$head" ]; then
  bad "Root: $ROOT is ${s:-?}/${h:-?} at ${r:0:7} (head ${head:0:7})"
fi
am_app_json $ROOT >"$AM_TMP/root.json"
for p in meridian-core meridian-edge; do
  jq -e --arg p "$p" '.status.resources[]? | select(.kind=="AppProject" and .name==$p)' "$AM_TMP/root.json" >/dev/null \
    || bad "Projects: AppProject $p does not exist or is not maintained by $ROOT, so what is deployed in it cannot be admitted"
done
jq -e '.status.resources[]? | select(.kind=="ApplicationSet" and .name=="meridian-edge")' "$AM_TMP/root.json" >/dev/null \
  || bad "Root: ApplicationSet meridian-edge is not maintained by $ROOT"
jq -e '.status.resources[]? | select(.kind=="Application" and .name=="meridian-core")' "$AM_TMP/root.json" >/dev/null \
  || bad "Root: Application meridian-core is not maintained by $ROOT"

# Git: on a fresh cluster the projects must exist before anything that uses them
am_yaml_docs_json "$AM_TMP/git/bootstrap" >"$AM_TMP/docs.json"
"$AM_PYTHON" - "$AM_TMP/docs.json" <<'PY' || fails=$((fails+1))
import json, sys
docs = json.load(open(sys.argv[1]))
def wave(d):
    a = (d.get("metadata") or {}).get("annotations") or {}
    return int(str(a.get("argocd.argoproj.io/sync-wave", "0")).strip() or 0)
projs = [d for d in docs if d.get("kind") == "AppProject"]
users = [d for d in docs if d.get("kind") in ("Application", "ApplicationSet")]
if len(projs) < 2:
    print("❌ Projects: the bootstrap folder in Git does not contain both AppProjects"); sys.exit(1)
pw = max(wave(p) for p in projs)
late = [d["metadata"]["name"] for d in users if not pw < wave(d)]
if late:
    print("❌ Projects: in Git, the AppProjects are not applied strictly before %s: a fresh bootstrap would create them together" % ", ".join(late)); sys.exit(1)
print("✅ Git applies the AppProjects before the Application and the ApplicationSet that use them")
PY

# ── ApplicationSet ──────────────────────────────────────────────────────────────
if kubectl -n argocd get applicationset meridian-edge -o json >"$AM_TMP/set.json" 2>/dev/null; then
  err="$(jq -r '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")][0].message // empty' "$AM_TMP/set.json")"
  [ -z "$err" ] || bad "ApplicationSet: meridian-edge reports an error: ${err:0:140}"
else
  bad "ApplicationSet: meridian-edge does not exist"
fi
for d in north south harbor; do
  app="meridian-edge-$d"
  if ! am_app_exists "$app"; then bad "ApplicationSet: Application $app was not generated"; continue; fi
  owner="$(am_app "$app" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
  [ "$owner" = meridian-edge ] || bad "ApplicationSet: Application $app is not generated by meridian-edge"
  ns="$(am_app "$app" '{.spec.destination.namespace}')"
  [ "$ns" = "meridian-$d" ] || bad "ApplicationSet: Application $app deploys to '${ns:-<none>}' instead of meridian-$d"
  s="$(am_app_sync $app)"; h="$(am_app_health $app)"; r="$(am_app_rev $app)"
  if [ "$s" != Synced ] || [ "$h" != Healthy ] || [ "$r" != "$head" ]; then
    bad "Edge: Application $app is ${s:-?}/${h:-?} at ${r:0:7} $(am_app_conditions "$app" | head -1 | cut -c1-150)"
  else
    b="$(am_http "http://meridian-edge.meridian-$d" "meridian-$d" 2 2>/dev/null)"
    [ "$b" = "meridian-edge v3.2" ] || bad "Edge: Service meridian-edge in meridian-$d answers '${b:-nothing}'"
  fi
done

# ── Projects ────────────────────────────────────────────────────────────────────
if kubectl -n argocd get appproject meridian-edge -o json >"$AM_TMP/pe.json" 2>/dev/null; then
  jq -e '[.spec.destinations[]? | select(.namespace=="*" or .server=="*")] | length == 0' "$AM_TMP/pe.json" >/dev/null \
    || bad "Projects: meridian-edge accepts every destination: the fix opened it up instead of adding the district"
  for d in north south harbor; do
    jq -e --arg n "meridian-$d" '[.spec.destinations[]? | select(.namespace==$n or .namespace=="meridian-*")] | length >= 1' "$AM_TMP/pe.json" >/dev/null \
      || bad "Projects: project meridian-edge does not admit namespace meridian-$d"
  done
  jq -e '(.spec.sourceRepos // []) | index("*") | not' "$AM_TMP/pe.json" >/dev/null || bad "Projects: meridian-edge accepts every source repository"
fi

# ── Core: namespace option, hook, service ───────────────────────────────────────
APP=meridian-core
if am_app_exists $APP; then
  s="$(am_app_sync $APP)"; h="$(am_app_health $APP)"; r="$(am_app_rev $APP)"
  if [ "$s" != Synced ] || [ "$h" != Healthy ] || [ "$r" != "$head" ]; then
    bad "Core: Application $APP is ${s:-?}/${h:-?} at ${r:0:7} $(am_app_conditions $APP | head -1 | cut -c1-150)"
  fi
  op="$(am_app_op $APP)"; oprev="$(am_app $APP '{.status.operationState.syncResult.revision}')"
  if [ "$op" != Succeeded ] || [ "$oprev" != "$head" ]; then
    bad "Core: the last sync of $APP is ${op:-missing} at ${oprev:0:7}: $(am_app $APP '{.status.operationState.message}' | cut -c1-140)"
  else
    am_app_json $APP | jq -e '[.status.operationState.syncResult.resources[]? | select(.kind=="Job" and .name=="meridian-core-smoke" and .hookType=="PostSync" and .hookPhase=="Succeeded")] | length == 1' >/dev/null \
      || bad "Hooks: the last sync of $APP did not run a passing PostSync smoke test (Job meridian-core-smoke)"
  fi
  am_app_json $APP | jq -e '(.spec.syncPolicy.syncOptions // []) | index("CreateNamespace=true")' >/dev/null \
    || bad "Core: Application $APP cannot deploy to a fresh cluster: namespace meridian-core is not created by the sync"
  jq -e '[.[] | select(.kind=="Application" and .metadata.name=="meridian-core") | (.spec.syncPolicy.syncOptions // []) | index("CreateNamespace=true")] | map(select(. != null)) | length >= 1' "$AM_TMP/docs.json" >/dev/null \
    || bad "Core: in Git, Application meridian-core does not create its namespace"
  b="$(am_http http://meridian-core.meridian-core meridian-core 2 2>/dev/null)"
  [ "$b" = "meridian-core v5.0" ] || bad "Core: Service meridian-core answers '${b:-nothing}' instead of 'meridian-core v5.0'"
else
  bad "Core: Application $APP does not exist"
fi
am_yaml_docs_json "$AM_TMP/git/core" >"$AM_TMP/core.json"
"$AM_PYTHON" - "$AM_TMP/core.json" <<'PY' || fails=$((fails+1))
import json, re, sys
docs = json.load(open(sys.argv[1]))
smoke = [d for d in docs if d.get("kind") == "Job" and d["metadata"]["name"] == "meridian-core-smoke"]
svcs = {d["metadata"]["name"]: d for d in docs if d.get("kind") == "Service"}
if not smoke:
    print("❌ Hooks: the smoke test Job is no longer in Git"); sys.exit(1)
c = smoke[0]["spec"]["template"]["spec"]["containers"][0]
cmd = " ".join((c.get("command") or []) + (c.get("args") or []))
if "curl" not in cmd:
    print("❌ Hooks: the smoke test in Git no longer calls the service"); sys.exit(1)
if any(x in cmd for x in ("|| true", "exit 0", ";true", "; true")):
    print("❌ Hooks: the smoke test in Git swallows its own errors: a test that cannot fail tests nothing"); sys.exit(1)
m = re.search(r"https?://([a-z0-9-]+)(?::(\d+))?", cmd)
if not m or m.group(1) not in svcs:
    print("❌ Hooks: the smoke test in Git calls a host that is not a Service of the release"); sys.exit(1)
port = int(m.group(2) or 80)
if port not in [p["port"] for p in svcs[m.group(1)]["spec"]["ports"]]:
    print("❌ Hooks: the smoke test in Git calls port %d, which the Service does not expose" % port); sys.exit(1)
print("✅ Git: the smoke test calls a real Service port and can fail")
PY

[ "$fails" = 0 ] || { echo "   $fails problem(s) left"; exit 1; }
am_pass "Mission control is green: bootstrap, projects, ApplicationSet fleet, core release"
