#!/bin/bash
set -uo pipefail
source "$AM_LIB"

SET=quota-fleet
kubectl -n argocd get applicationset "$SET" >/dev/null 2>&1 \
  || am_fail "ApplicationSet '$SET' does not exist in namespace argocd"
kubectl -n argocd get applicationset "$SET" -o json | jq -e \
  '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' >/dev/null \
  || am_fail "ApplicationSet '$SET' reports an error condition"

kubectl -n argocd get secrets -l argocd.argoproj.io/secret-type=cluster -o json \
  | jq -e '[.items[] | select((.data.name // "" | @base64d) == "staging")] | length == 1' >/dev/null \
  || am_fail "No cluster named 'staging' is registered any more"

have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name] | sort | join(" ")')"
[ "$have" = "quota-staging" ] || am_fail "The Applications in argocd are [${have}], expected [quota-staging]"

app=quota-staging
owner="$(am_app "$app" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
[ "$owner" = "$SET" ] || am_fail "Application '$app' is not generated by ApplicationSet '$SET' (owner: ${owner:-none})"
dname="$(am_app "$app" '{.spec.destination.name}')"
dserver="$(am_app "$app" '{.spec.destination.server}')"
{ [ "$dname" = staging ] || [ "$dserver" = https://kubernetes.default.svc.cluster.local ]; } \
  || am_fail "Application '$app' does not deploy to the staging cluster (destination: ${dname:-$dserver})"
am_require_app_at_head "$app" quota-service
body="$(am_http http://quota-api.quota quota)" || am_fail "Service quota-api in namespace quota does not answer"
[ "$body" = "quota-api v3" ] || am_fail "Service quota-api answers '$body'"
am_pass "quota-api is deployed to the staging cluster by the ApplicationSet"
