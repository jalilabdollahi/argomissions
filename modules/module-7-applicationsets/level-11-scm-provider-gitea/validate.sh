#!/bin/bash
set -uo pipefail
source "$AM_LIB"

SET=mesh-fleet
kubectl -n argocd get applicationset "$SET" -o json >"$AM_TMP/set.json" 2>/dev/null \
  || am_fail "ApplicationSet '$SET' does not exist in namespace argocd"
jq -e '.spec.generators | length == 1 and (.[0].scmProvider.gitea != null)' "$AM_TMP/set.json" >/dev/null \
  || am_fail "ApplicationSet '$SET' no longer discovers repositories through the Gitea SCM provider generator"
jq -e '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True")] | length == 0' "$AM_TMP/set.json" >/dev/null \
  || am_fail "ApplicationSet '$SET' reports an error condition: $(jq -r '[.status.conditions[]? | select(.type=="ErrorOccurred" and .status=="True") | .message][0]' "$AM_TMP/set.json")"
am_ok "ApplicationSet '$SET' generates without errors"

want="mesh-ember mesh-pinger mesh-quill"
have="$(kubectl -n argocd get applications -o json | jq -r '[.items[].metadata.name] | sort | join(" ")')"
[ "$have" = "$want" ] || am_fail "The Applications in argocd are [${have}], expected [$want]"

for r in pinger quill ember; do
  app="mesh-$r"
  owner="$(am_app "$app" '{.metadata.ownerReferences[?(@.kind=="ApplicationSet")].name}')"
  [ "$owner" = "$SET" ] || am_fail "Application '$app' is not generated by ApplicationSet '$SET' (owner: ${owner:-none})"
  [ "$(am_app "$app" '{.spec.destination.namespace}')" = "$app" ] || am_fail "Application '$app' does not deploy to namespace $app"
  am_require_app_at_head "$app" "$app"
  body="$(am_http "http://$app.$app" "$app")" || am_fail "Service $app in namespace $app does not answer"
  [ "$body" = "$app v1" ] || am_fail "Service $app answers '$body'"
done
am_pass "every mesh-* repository is an Application and wiki-notes is not"
